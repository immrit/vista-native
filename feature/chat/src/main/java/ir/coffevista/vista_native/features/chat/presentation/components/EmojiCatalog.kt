class RecentEmojiStore(context: Context) {
    private val prefs = context.getSharedPreferences(PREF_NAME, Context.MODE_PRIVATE)

    fun getRecent(): List<String> {
        val saved = prefs.getString(KEY_RECENTS, null) ?: return defaultRecents
        val list = saved.split(",").filter { it.isNotBlank() }
        return if (list.isEmpty()) defaultRecents else list
    }

    fun addRecent(emoji: String) {
        val current = getRecent().toMutableList()
        current.remove(emoji)
        current.add(0, emoji)
        val capped = current.take(36)
        prefs.edit().putString(KEY_RECENTS, capped.joinToString(",")).apply()
    }

    private companion object {
        const val PREF_NAME = "vista_recent_emojis"
        const val KEY_RECENTS = "recents_list"
        val defaultRecents = listOf(
            "😂", "❤️", "😍", "👍", "🔥", "😭", "😊", "🥰",
            "🎉", "🙏", "😎", "🤔", "✨", "💯", "👏", "🤣",
            "😘", "😉", "🙌", "😁", "💔", "🥺", "😴", "👌",
        )
    }
}
